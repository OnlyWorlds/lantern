// Writes src/type-icons.ts: one path per element type, the glyph the SDK's ELEMENT_ICONS names
// (the ecosystem's per-type mark, as Atlas shows it), taken from @material-symbols/svg-400's
// outlined set (Apache-2.0). Only these 22 paths ship; Atlas's whole icon font is 3.8 MB.
// Per Seethe: on Catch's "What is it?" picker and a world's type tiles, not in the chips.
// Run: node walk/type-icons.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { ELEMENT_ICONS } from '@onlyworlds/sdk';

const dir = 'node_modules/@material-symbols/svg-400/outlined';
const version = JSON.parse(readFileSync('node_modules/@material-symbols/svg-400/package.json', 'utf8')).version;
// Material Symbols renamed two of the SDK's names; the font still answers to the old ones as
// ligature aliases (which is how Atlas shows them), the per-icon SVGs only to the new.
const RENAMED = { auto_fix_normal: 'wand_stars', push_pin: 'keep' };
const lines = [];
for (const [type, name] of Object.entries(ELEMENT_ICONS).sort()) {
  const svg = readFileSync(`${dir}/${RENAMED[name] ?? name}.svg`, 'utf8');
  if (!svg.includes('viewBox="0 -960 960 960"')) throw new Error(`${name}: unexpected viewBox`);
  const paths = [...svg.matchAll(/<path d="([^"]+)"\/>/g)].map((m) => m[1]);
  if (paths.length !== 1) throw new Error(`${name}: ${paths.length} paths`);
  if (!/^[MmLlHhVvCcSsQqTtAaZz0-9.,\- ]+$/.test(paths[0])) throw new Error(`${name}: not a plain path`);
  lines.push(`  ${type}: '${paths[0]}', // ${name}`);
}
writeFileSync(
  'src/type-icons.ts',
  [
    `// Generated by walk/type-icons.mjs from @material-symbols/svg-400 ${version} (Apache-2.0), outlined:`,
    "// the glyph the SDK's ELEMENT_ICONS names for each type. Do not edit by hand. viewBox 0 -960 960 960.",
    'export const TYPE_ICON_PATHS: Record<string, string> = {',
    ...lines,
    '};',
    '',
  ].join('\n'),
);
console.log(`src/type-icons.ts: ${lines.length} types from ${version}`);
